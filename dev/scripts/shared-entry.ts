// Evaluated by dev/build.mjs (bundled for Node) to export what the stock-Hermes
// fallback shares with the Desktop plugin: the refinement instructions and the
// intent rules (shared.json), and the TypeScript checker's verdicts on
// dev/test/parity/inputs.json (the Python port must reach the same ones).
import { CLAUSE_BREAK, NEGATED_AFTER, NEGATED_BEFORE, NEGATION_LOOKBACK, RULES } from '../src/intent'
import { checkPreservation } from '../src/preservation'
import { buildRefinementCall, MAX_REFINE_CHARS } from '../src/prompt'
import type { RefinementStyle, RequestDepth } from '../src/types'

const DEPTHS: RequestDepth[] = ['auto', 'polish', 'clarify', 'deepen']
const STYLES: Exclude<RefinementStyle, 'custom'>[] = ['auto', 'clarity', 'technical', 'research', 'creative', 'agentic']
const MARK = '\u0000DRAFT\u0000'

const pattern = (re: RegExp) => ({ source: re.source, flags: re.flags })

export function shared() {
  const calls: Record<string, Record<string, { instructions: string; max_tokens: number; temperature: number }>> = {}

  for (const depth of DEPTHS) {
    calls[depth] = {}

    for (const style of STYLES) {
      const call = buildRefinementCall({ text: MARK, attachmentLabels: [], style, depth })
      calls[depth][style] = { instructions: call.instructions, max_tokens: call.maxTokens, temperature: call.temperature }
    }
  }

  const input = buildRefinementCall({ text: MARK, attachmentLabels: [], style: 'auto', depth: 'auto' }).input

  return {
    note: 'Generated by build.mjs from src/prompt.ts and src/intent.ts. Do not edit.',
    max_chars: MAX_REFINE_CHARS,
    depths: DEPTHS,
    styles: STYLES,
    input_template: input.replace(MARK, '{draft}'),
    calls,
    intent: {
      rules: RULES.map(rule => ({
        kind: rule.kind,
        trigger: pattern(rule.trigger),
        allowed_by: rule.allowedBy ? pattern(rule.allowedBy) : null,
        symmetric: Boolean(rule.symmetric)
      })),
      negated_before: pattern(NEGATED_BEFORE),
      clause_break: pattern(CLAUSE_BREAK),
      negated_after: pattern(NEGATED_AFTER),
      lookback: NEGATION_LOOKBACK
    }
  }
}

export function parity(inputs: [string, string][]) {
  return inputs.map(([original, candidate]) => ({
    original,
    candidate,
    issues: checkPreservation(original, candidate).issues
  }))
}
